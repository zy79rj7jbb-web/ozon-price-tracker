const findProduct = db.prepare(`
  SELECT id, name, is_active
  FROM products
  WHERE ozon_product_id = ?
`);

const insertProduct = db.prepare(`
  INSERT INTO products (
    ozon_product_id,
    name,
    is_active
  )
  VALUES (?, ?, 1)
`);

const updateProduct = db.prepare(`
  UPDATE products
  SET name = ?, is_active = 1
  WHERE ozon_product_id = ?
`);

let added = 0;
let updated = 0;
let unchanged = 0;

const importProducts = db.transaction(() => {
  for (const [ozonProductId, name] of products) {
    const existing = findProduct.get(ozonProductId);

    if (!existing) {
      insertProduct.run(ozonProductId, name);
      added++;
      continue;
    }

    if (existing.name !== name || existing.is_active !== 1) {
      updateProduct.run(name, ozonProductId);
      updated++;
    } else {
      unchanged++;
    }
  }
});

importProducts();

console.log(`Всего товаров в импорте: ${products.length}`);
console.log(`Добавлено: ${added}`);
console.log(`Обновлено: ${updated}`);
console.log(`Без изменений: ${unchanged}`);
